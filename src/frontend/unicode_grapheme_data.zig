pub fn isExtendOrSpacingMark(cp: u21) bool {
    var low: usize = 0;
    var high: usize = ranges.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        const range = ranges[mid];
        if (cp < range.first) high = mid else if (cp > range.last) low = mid + 1 else return true;
    }
    return false;
}
